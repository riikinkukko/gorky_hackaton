def _target_noun_fix(desc: str) -> str:
    """«звонок Анне» → «позвонить Анне», «встретиться с Марией» → «встречу с Марией».

    Резолвер диалога сравнивает основы слов с названием: «Позвонить Анне» и «звонок» не
    совпадают, поэтому приводим к глаголу из названий (данные: «Позвонить X»).
    """
    desc = re.sub(r"(?i)(?<![а-яё])звон(?:ок|ка|ку)\s+(?=[А-ЯЁ])", "позвонить ", desc)
    desc = re.sub(r"(?i)(?<![а-яё])встретиться(?![а-яё])", "встречу", desc)
    for noun, verb in _NOUN_TO_VERB.items():  # «подготовку акта» → «подготовить акт…»
        desc = re.sub(r"(?i)(?<![а-яё])" + noun + r"(?![а-яё])", verb, desc)
    return desc


class RuleRouter:
    def __init__(
        self, resolver: RuleDateResolver | None = None, normalizer: EntityNormalizer | None = None
    ) -> None:
        self.dates = resolver or RuleDateResolver()
        self.ents = normalizer or default_normalizer()

    # ---------- публичное ----------

    def route(self, text: str, state: DialogState | None, now: datetime) -> Command | None:
        low = simple_norm(text.strip())
        if re.match(r"^(?:а\s+)?можно ли\b", low) and not self.dates.extract(text, now).found:
            # «а можно ли поставить две встречи на одно время» — вопрос о возможностях
            return self._cmd(Intent.SMALLTALK, text.strip(), Slots(), 0.9)
        t, penalty = self._preclean(text, now)
        if not t:
            return self._cmd(Intent.UNKNOWN, text.strip(), Slots(), 0.9)
        cmd = self._route(t, state, now)
        if cmd is not None:
            cmd = self._date_from_context(cmd, state)
            cmd = self._there_from_context(cmd, t, state)
            sl = cmd.slots
            if (
                cmd.intent == Intent.SEARCH
                and not (
                    sl.query
                    or sl.participants
                    or sl.organization
                    or sl.when
                    or sl.type
                    or sl.status
                )
                and sl.tense in (None, "any")
            ):
                # «найди», «найди найди найди» — искать нечего: переспрос, а не «все записи»
                cmd = self._cmd(Intent.UNKNOWN, cmd.raw_text, Slots(), 0.6)
        if cmd is not None and penalty:
            # во фразе были неуверенность или мусор: результат правил — только подсказка
            cmd = cmd.model_copy(update={"confidence": min(cmd.confidence, PENALTY_CONF)})
        return cmd

    @staticmethod
    def _truncated_update(text: str) -> str | None:
        """«неси/еси/реси/ренеси …» в начале + указание на запись или новое время → «перенеси …».

        Только если дальше есть ссылка на существующую запись (её, эту, встречу, задачу…) или
        «на + дата/время»: «неси хлеб» так не разбирается.
        """
        m = STUB_UPDATE.match(text.strip())
        if not m:
            return None
        rest = text.strip()[m.end() :].strip(" ,")
        low = simple_norm(rest)
        if not (STUB_REFERENCE.search(low) or re.search(r"(?<![а-я])на\s+\S", low)):
            return None
        return "Перенеси " + rest

    @staticmethod
    def _there_from_context(cmd: Command, t: str, state: DialogState | None) -> Command:
        """«Что у меня в субботу?» → «перенеси встречу оттуда на воскресенье» (день из списка);
        «… → перенеси встречу с Иваном туда же на одиннадцать» (новый день — из списка)."""
        last = state.last_command if state else None
        if (
            cmd.intent not in (Intent.UPDATE, Intent.DELETE, Intent.COMPLETE)
            or last is None
            or last.intent != Intent.LIST
            or last.slots.when is None
            or last.slots.when.start is None
        ):
            return cmd
        lw = last.slots.when
        assert lw.start is not None
        if lw.end is not None and (lw.end - lw.start).days > 1:
            return cmd
        low = simple_norm(t)
        slots = cmd.slots.model_copy()
        if _FROM_THERE.search(low) and slots.when is None:
            slots.when = lw.model_copy()
        elif _TO_THERE.search(low) and cmd.intent == Intent.UPDATE:
            nw = slots.new_when
            day = lw.start
            if nw is None or nw.start is None:
                slots.new_when = TimeSpec(text=lw.text, start=day, has_date=True)
            elif not nw.has_date:
                start = nw.start.replace(year=day.year, month=day.month, day=day.day)
                slots.new_when = nw.model_copy(update={"start": start, "has_date": True})
        else:
            return cmd
        return cmd.model_copy(update={"slots": slots})

    @staticmethod
    def _date_from_context(cmd: Command, state: DialogState | None) -> Command:
        """«Покажи встречи на понедельник» → «добавь ещё созвон в три» — понедельник, 15:00."""
        w = cmd.slots.when
        last = state.last_command if state else None
        there = bool(_THAT_DAY.search(simple_norm(cmd.raw_text)))
        if (
            cmd.intent != Intent.CREATE
            or (w is None and not there)
            or (w is not None and (w.start is None or not w.has_time or w.has_date))
            or last is None
            or last.intent != Intent.LIST
            or last.slots.when is None
            or last.slots.when.start is None
        ):
            return cmd
        lw = last.slots.when
        assert lw.start is not None
        if lw.end is not None and (lw.end - lw.start).days > 1:
            return cmd  # список за неделю — день не определён
        if w is None:  # «добавь туда купить подарок» — день из прошлого списка
            day = lw.start.replace(hour=0, minute=0)
            spec = TimeSpec(text=lw.text, start=day, has_date=True)
            return cmd.model_copy(update={"slots": cmd.slots.model_copy(update={"when": spec})})
        assert w.start is not None
        start = w.start.replace(year=lw.start.year, month=lw.start.month, day=lw.start.day)
        slots = cmd.slots.model_copy(
            update={"when": w.model_copy(update={"start": start, "end": None, "has_date": True})}
        )
        return cmd.model_copy(update={"slots": slots})

    @staticmethod
    def _fix_first_cut(text: str) -> str:
        """«кие планы» → «какие планы», «то у меня» → «что у меня», «кажи» → «покажи»."""
        m = re.match(r"([А-Яа-яЁё]+)(\s+|$)", text)
        if not m:
            return text
        w = simple_norm(m.group(1))
        rest = text[m.end() :]
        nxt = simple_norm(rest.split()[0]) if rest.split() else ""
        if w in _FIRST_CUT:
            return _FIRST_CUT[w] + m.group(2) + rest
        if w in _FIRST_CUT_CTX:
            full, ctx = _FIRST_CUT_CTX[w]
            if re.match(ctx, nxt):
                return full + m.group(2) + rest
        return text

    def _date_windows(self, part: str, now: datetime) -> list[tuple[int, int, bool, bool]]:
        """Окна слов, которые целиком — выражение даты/времени: (start, end, has_date, has_time)."""
        words = [(m.start(), m.end()) for m in re.finditer(r"\S+", part)]
        out: list[tuple[int, int, bool, bool]] = []
        for i in range(len(words)):
            for j in range(min(len(words), i + 6), i, -1):
                a, b = words[i][0], words[j - 1][1]
                frag = part[a:b].strip(" ,")
                dp = self.dates.extract(frag, now, "point")
                if dp.spec is None or not self._only_dates(frag, dp):
                    continue
                left = self._clean(remove_spans(frag, dp.spans))
                if left and not re.fullmatch(r"(?:(?:в|во|на|к|с|до|по|около)\s*)+", left):
                    continue
                out.append((a, b, dp.has_date, dp.spec.has_time))
                break
        return out

    def _self_correction(self, text: str, now: datetime) -> str:
        """«в среду, ой нет, в четверг» → «в четверг»; «в девять ой нет в десять» → «в десять».

        Из части до маркера убираем выражения того же вида, что после маркера (время → время,
        дата → дата). «купить молоко ой хлеб» — без даты: заменяем ближайшее слово той же
        части речи.
        """
        for _ in range(3):
            m = _SELF_CORR.search(text)
            if not m or m.start() == 0:
                break
            before, after = text[: m.start()], text[m.end() :]
            marker = self._clean(m.group(0))
            after_core = _AFTER_LEAD.sub("", after)
            # «на час позже, хотя нет, на два» → «на два часа позже»
            sb = re.search(
                r"на\s+(?:\S+\s+)?" + _SHIFT_UNITS + r"\s+" + _SHIFT_DIR + r"\s*$", before, re.I
            )
            sa = re.match(r"на\s+(\S+)(?:\s+" + _SHIFT_UNITS + r")?\s*$", after_core, re.I)
            if sb and sa:
                unit = sa.group(2) or {"час": "часа", "день": "дня", "минуту": "минуты"}.get(
                    sb.group(1).lower(), sb.group(1)
                )
                text = f"{before[: sb.start()]} на {sa.group(1)} {unit} {sb.group(2)}".strip()
                continue
            ad = self.dates.extract(after_core, now, "point")
            starts_with_date = bool(ad.spans) and ad.spans[0][0] <= 1
            if starts_with_date and ad.spec is not None:
                want_time, want_date = ad.spec.has_time, ad.has_date
                cut: list[tuple[int, int]] = []
                for a, b, hd, ht in self._date_windows(before, now):
                    same = (want_time and ht and not (hd and not want_date)) or (
                        want_date and hd and not (ht and not want_time)
                    )
                    if same and all(b <= x or a >= y for x, y in cut):
                        cut.append((a, b))
                if not cut:
                    break
                kept = remove_spans(before, cut)
                text = f"{kept} {after_core}".strip()
                continue
            # «через два часа а нет через три» — единицу берём из исправляемой части
            mm = re.match(r"(через|в|на)\s+(\S+)(?=\s|$)", after_core)
            unit1 = re.search(r"через\s+(час|минуту|день|неделю)\s*$", before)
            if mm and mm.group(1) == "через" and unit1 and ad.spec is None:
                plural = {"час": "часа", "минуту": "минуты", "день": "дня", "неделю": "недели"}
                fixed = f"через {mm.group(2)} {plural[unit1.group(1)]}"
                text = f"{before[: unit1.start()]} {fixed}{after_core[mm.end() :]}".strip()
                continue
            if mm and ad.spec is None:
                bw = re.search(mm.group(1) + r"\s+\S+\s+(\S+)\s*$", before)
                if bw:
                    fixed = f"{mm.group(1)} {mm.group(2)} {bw.group(1)}"
                    text = f"{before[: bw.start()]} {fixed}{after_core[mm.end() :]}".strip()
                    continue
            pm = re.match(r"(с|со|про|по|для|у|о|об)\s+\S", after_core, re.I)
            if pm and ad.spec is None:
                # «с Иваном ой нет с Марией», «с Вектором а нет с Орбитой» — та же роль
                prev = list(re.finditer(r"(?<![а-яё])" + pm.group(1) + r"\s+", before, re.I))
                if prev:
                    text = f"{before[: prev[-1].start()]} {after_core}".strip()
                    continue
            aw = after_core.split()
            if 1 <= len(aw) <= 2 and ad.spec is None:
                # «отметь смету выполненной, а нет, подожди, акт» → «отметь акт выполненной»
                q = self.ents.morph.parse(aw[0].lower())[0]
                bwords = before.split()
                nouns = [
                    i
                    for i, w in enumerate(bwords)
                    if self.ents.morph.parse(w.lower().strip(",."))[0].tag.POS == "NOUN"
                ]
                if q.tag.POS == "NOUN" and nouns:
                    i = nouns[-1]
                    text = " ".join([*bwords[:i], after_core, *bwords[i + 1 :]])
                    continue
            if marker in _SELF_CORR_SOFT and after_core.split():
                bwords = before.split()
                if bwords:
                    text = " ".join([*bwords[:-1], after_core])
                    continue
            break
        return re.sub(r"\s{2,}", " ", text).strip()

    def _polite_to_command(self, text: str) -> str:
        """«Можешь перенести, пожалуйста, встречу …?» → «перенести, пожалуйста, встречу …».

        Только перед глаголом совершенного вида: «ты можешь записывать встречи?» — вопрос о
        возможностях (его разбирает CAPABILITY), а не команда.
        """
        m = POLITE.match(text)
        if not m:
            return text
        rest = text[m.end() :]
        w = re.match(r"[А-Яа-яЁё]+", rest)
        if not w:
            return text
        if not self._infinitive(w.group(0)) or self._imperfective(w.group(0)):
            return text
        return re.sub(r"\s*\?+\s*$", "", rest)

    def _preclean(self, text: str, now: datetime | None = None) -> tuple[str, bool]:
        """Приветствия, «наверное», идиомы и просьба о совете — до разбора (живой тест 22.10).

        24.10 (adversarial): мат и паразиты в начале, обрезанное ASR первое слово, вежливые
        обёртки, самопоправки «в среду, ой нет, в четверг».
        """
        t = text.strip()
        penalty = bool(HEDGES.search(t) or GARBAGE.search(t))
        out = _GREETING_LEAD.sub("", t)
        out = PROFANITY.sub(" ", out).strip(" ,")
        out = _LEAD_SLANG.sub("", out)
        out = _GREETING_LEAD.sub("", out)
        out = self._fix_first_cut(out)
        out = _WISH.sub(lambda m: _WISH_VERB[m.group(1).lower()] + " ", out)
        out = self._polite_to_command(out)
        out = _WRAPPERS.sub("", out) or out
        out = self._fix_first_cut(out)
        out = re.sub(r"(?i)\b(\w+)(?:\s+\1\b)+", r"\1", out)  # «встреча встреча встреча»
        # «в 13:30 с 13:30 до 15:30» — повтор начала перед интервалом (стенд 23.10)
        out = re.sub(r"(?i)(?<![а-яё])в\s+(\d{1,2}[:.]\d{2})\s+(?=с\s+\1(?!\d))", "", out)
        if now is not None:
            out = self._self_correction(out, now)
        out = ADVICE_TAIL.sub("", out)
        out = GARBAGE.sub(" ", out)
        out = HEDGES.sub(" ", out)
        # «на полчаса пораньше» — направление сдвига, а не смягчение
        out = re.sub(
            r"(?i)(полчаса|полчасика|минут\w*|час\w*|дн\w*|день|недел\w*)\s+пораньше",
            r"\1 раньше",
            out,
        )
        out = SOFTENERS.sub(" ", out)
        out = re.sub(r"\s+([,.!?:])", r"\1", out)
        out = re.sub(r"(?:,\s*){2,}", ", ", out)
        out = re.sub(r"\s{2,}", " ", out).strip(" ,")
        if not out:
            if penalty:
                return "", True  # фраза целиком из мусора («ну, ещё что-нибудь») → unknown
            return t, False  # «Привет» целиком — это smalltalk, разбираем как есть
        return out, penalty

    def _route(self, text: str, state: DialogState | None, now: datetime) -> Command | None:
        stub = self._truncated_update(text)
        if stub is not None:
            # QA-18: «Неси встречу на субботу» — обрезанное «Перенеси». Понимаем как перенос,
            # но с низкой уверенностью: по «её/встречу» диалог переспросит, а не выполнит молча
            cmd = self._update(stub, now)
            return cmd.model_copy(
                update={"confidence": min(cmd.confidence, STUB_CONF), "raw_text": text.strip()}
            )
        t = text.strip()
        clean = self._clean(t)
        if not clean or not FILLERS.sub("", clean).strip():
            return self._cmd(Intent.UNKNOWN, t, Slots(), 1.0)
        t = self._strip_fillers(t)
        t = self._first_command(t, now)
        clean = self._clean(t)

        if YES.fullmatch(clean):
            return self._cmd(Intent.CONFIRM, t, Slots(), 0.95)
        if NO.fullmatch(clean):
            awaiting = state.awaiting if state else None
            if clean in ("отмена", "отмени") and not awaiting:
                return self._cmd(Intent.UNDO, t, Slots(), 0.95)
            return self._cmd(Intent.REJECT, t, Slots(), 0.95)
        if UNDO.fullmatch(clean):
            if state and state.awaiting:
                return self._cmd(Intent.REJECT, t, Slots(), 0.95)
            return self._cmd(Intent.UNDO, t, Slots(), 0.95)
        if state and state.awaiting and re.fullmatch(r"(?:отмени|отмена|удали) (?:все|всё)", clean):
            return self._cmd(Intent.REJECT, t, Slots(), 0.95)
        ma = _ABOUT_DATE.match(clean)
        if ma:  # «ой нет, я про понедельник» — уточнение дня вопроса, а не перенос записи
            dpa = self.dates.extract(ma.group(1), now, "period")
            last = state.last_command if state else None
            if dpa.found and (last is None or last.intent in (Intent.LIST, Intent.SEARCH)):
                slots = last.slots.model_copy(deep=True) if last else Slots()
                slots.when = dpa.spec
                return self._cmd(last.intent if last else Intent.LIST, t, slots, 0.9)
        corr = self._correction(t, clean, now, state)
        if corr:
            return corr
        if NONSENSE.fullmatch(clean):
            return self._cmd(Intent.SMALLTALK, t, Slots(), 0.9)  # «алло, слышно меня?», «бла бла»
        if HELP_PHRASES.search(clean) or self._capability_question(clean):
            return self._cmd(Intent.SMALLTALK, t, Slots(), 0.95)  # справка: что умею
        if SMALLTALK.match(clean) and len(clean.split()) <= 4:
            return self._cmd(Intent.SMALLTALK, t, Slots(), 0.9)
        if OUT_OF_SCOPE.search(clean) and not CREATE_TRIGGER.search(clean):
            return self._cmd(Intent.UNKNOWN, t, Slots(), 0.9)

        dp = self.dates.extract(t, now, "period")
        if not dp.found and LIST_ALL.fullmatch(clean) and _LIST_ALL_NEEDS.search(clean):
            return self._list_upcoming(t, now)
        # «та встреча, что будет завтра, перенеси…», «чё-то не успеваю, двинь…» — не вопрос
        qclean = clean
        if UPDATE.search(clean) or DELETE.search(clean) or COMPLETE.search(clean):
            qclean = re.sub(r"(?:котор\w+|что) (?:был\w*|будет|стоит)", " ", clean)
            qclean = re.sub(r"^(?:что|че|чего)[- ]то\s+", "", qclean).strip()
        is_question = (
            t.rstrip().endswith("?")
            or bool(QUESTION_START.match(qclean))
            or bool(QUESTION_ANY.search(qclean))
            or bool(re.search(r"(?<![а-я])(когда|где|во сколько)$", qclean))
        )
        if is_question and CREATE_TRIGGER.match(clean) and dp.spec is not None and dp.spec.has_time:
            is_question = False  # «не забудь, что у меня в понедельник собеседование в 11»
        follow = self._follow_up(t, clean, state, now, dp)
        if follow is not None:
            return follow

        create_pos = _pos(CREATE_TRIGGER, clean)
        implicit = self._implicit_update(t, clean, now, create_pos, is_question)
        if implicit is not None:
            return implicit
        looks_search = bool(re.search(r"(?<![а-яё])(?:найди|найти|поищи|поискать)", clean))
        if _pos(COMPLETE, clean) < create_pos or (
            COMPLETE_I_DID.match(clean) and not is_question and not looks_search
        ):
            if not SEARCH_START.match(clean):
                return self._target_cmd(Intent.COMPLETE, t, now, verb_re=COMPLETE)
        if DELETE.match(clean) or (_pos(DELETE, clean) < create_pos and not is_question):
            return self._target_cmd(Intent.DELETE, t, now, verb_re=DELETE)
        if _pos(UPDATE, clean) < create_pos and not is_question:
            return self._update(t, now)
        if (
            not is_question
            and create_pos > len(clean)
            and not NEED.search(clean)
            and not SEARCH_START.match(clean)
            and self._done_statement(clean)
        ):
            return self._target_cmd(Intent.COMPLETE, t, now, verb_re=_DONE_LEAD)

        if (
            dp.found
            and (is_question or LIST_CUE.search(clean))
            and not SEARCH_START.match(clean)
            and not (CREATE_TRIGGER.search(clean) and not QUESTION_START.match(clean))
            and not NEED.search(clean)
            and not self._has_content(t, dp, strict=True)
        ):
            return self._list(t, now, dp)  # «чё там у меня на завтра», «завтра какие задачи»
        if WEAK_SEARCH.match(clean) and dp.found and not self._has_content(t, dp):
            return self._list(t, now, dp)  # «Что было вчера?» — это список за период
        if SEARCH_START.match(clean) or (
            is_question and SEARCH_START.search(clean) and not dp.found
        ):
            return self._search(t, now, dp)

        if is_question and dp.found and not CREATE_TRIGGER.match(clean):
            if self._has_content(t, dp):
                return self._search(t, now, dp)  # «Какие встречи с Иваном были в прошлом году?»
            return self._list(t, now, dp)
        if dp.found and self._only_dates(t, dp):
            return self._list(t, now, dp)  # «А на следующей неделе?»

        if CREATE_TRIGGER.search(clean) and not is_question:
            return self._create(t, now, 0.92)
        if not is_question and MEETING_START.match(clean):
            words = clean.split()
            if len(words) > 1 and len({w[:5] for w in words}) == 1:
                return self._cmd(Intent.UNKNOWN, t, Slots(), 0.6)  # «созвон созвонился созвонимся»
            return self._create(t, now, 0.85)  # «встреча с Петром после праздников», «встреча с»
        if not is_question and (NEED.search(clean) or self._declares_meeting(t, clean, dp)):
            return self._create(t, now, 0.85 if dp.found else 0.75)

        if not is_question and (dp.recurrence or (dp.spec and dp.spec.has_time and dp.has_date)):
            return self._create(t, now, 0.8)  # «в субботу в 12 день рождения Ани»
        if (
            not is_question
            and dp.has_date
            and self._starts_with_infinitive(remove_spans(t, dp.spans))
        ):
            return self._create(t, now, 0.85)  # «На 31 зарегистрировать команду»
        if not is_question and self._starts_with_infinitive(t):
            return self._create(t, now, 0.75)  # «купить хлеб» — как заголовки в данных
        if is_question and not dp.found and not SEARCH_START.match(clean):
            if (
                not self._has_content(t, dp, strict=True)
                and self.ents.tense(t) != "past"
                and not STATUS_OPEN.search(clean)
                and not STATUS_DONE.search(clean)
                and (
                    self._type_by_noun(clean)
                    or re.match(r"^(?:что|чё|че|чо) у (?:меня|нас)", clean)
                )
            ):
                rest = re.sub(r"^(?:что|чё|че|чо|шо) у (?:меня|нас)\s*", "", clean)
                if re.match(r"(?:в|во)\s+\S+", rest):
                    # «что у меня в голове / в холодильнике / в тринадцатом месяце» — не про планы
                    return self._cmd(Intent.UNKNOWN, t, Slots(), 0.6)
                return self._list_upcoming(t, now)  # «чё по задачам», «что у меня после праздников»
        if is_question:
            if self._is_plain_list(clean):
                return self._list(t, now, dp)
            return self._search(t, now, dp, confidence=0.86 if self._has_content(t, dp) else 0.75)
        if self._looks_like_search_phrase(t):
            return self._search(t, now, dp, confidence=0.75)
        return None

    def fallback(self, text: str, state: DialogState | None, now: datetime) -> Command:
        """Когда LLM недоступен: лучшая догадка правилами вместо отказа."""
        cmd = self.route(text, state, now)
        if cmd is not None and self._empty_search(cmd):
            # «Привет, мне встречу, после дождичка…»: искать нечего — лучше переспросить
            return self._cmd(Intent.UNKNOWN, cmd.raw_text, Slots(), 0.3).model_copy(
                update={"source": "fallback"}
            )
        if cmd is not None:
            return cmd.model_copy(update={"source": "fallback"})
        dp = self.dates.extract(text, now, "point")
        clean = self._clean(text)
        if dp.found and (LIST_CUE.search(clean) or QUESTION_START.match(clean)):
            dpp = self.dates.extract(text, now, "period")
            c = self._list(text, now, dpp)  # вопрос с датой — никогда не создание
        elif dp.found:
            c = self._create(text, now, 0.5)
        elif len(self._clean(text).split()) >= 2:
            c = self._search(text, now, dp, confidence=0.4)
            if self._empty_search(c):  # «ну и что» — искать нечего
                c = self._cmd(Intent.UNKNOWN, text, Slots(), 0.3)
        else:
            c = self._cmd(Intent.UNKNOWN, text, Slots(), 0.3)
        return c.model_copy(update={"source": "fallback"})

    @staticmethod
    def _empty_search(cmd: Command) -> bool:
        s = cmd.slots
        return cmd.intent == Intent.SEARCH and not (
            s.participants or s.organization or s.query or s.when or s.tense != "any"
        )

    # ---------- распознавание ----------

    @staticmethod
    def _clean(t: str) -> str:
        s = simple_norm(t)
        s = re.sub(r"[?!.,;:«»\"()—–-]+", " ", s)
        return re.sub(r"\s+", " ", s).strip()

    @staticmethod
    def _strip_fillers(t: str) -> str:
        out = FILLERS.sub(" ", t)
        out = re.sub(r"\s+([,.!?:])", r"\1", out)
        out = re.sub(r"^[\s,.:;—–-]+", "", out)
        return re.sub(r"\s{2,}", " ", out).strip() or t

    def _has_content(self, t: str, dp: DateParse, *, strict: bool = False) -> bool:
        """Есть ли в вопросе люди, компании или тема — тогда это поиск, а не список за период.

        strict: тема засчитывается, только если это известная тема словаря (договор, CRM…),
        а не случайное слово («опять», «ждать», «стояло»).
        """
        rest = remove_spans(t, dp.spans) if dp.found else t
        ls = self.ents.lemmas(rest)
        if self.ents.people(rest, ls) or self.ents.organizations_in(rest, ls):
            return True
        q = self.ents.expand_query(rest, lemmas=ls)
        if not q:
            return False
        if strict:
            topics = {c for _, c in self.ents.phrases}  # глаголы («глянь» → проверить) — не тема
            return any(term in topics for term in q.split()) or any(
                c in q for c in topics if " " in c
            )
        terms = [
            w
            for w in q.split()
            if self.ents.type_words.get(w.replace("ё", "е")) is None and w not in _LIST_WORDS
        ]
        return bool(terms)

    def _follow_up(
        self, t: str, clean: str, state: DialogState | None, now: datetime, dp: DateParse
    ) -> Command | None:
        """«А на следующей неделе?», «А следующая?», «А с Марией?» — продолжение прошлой команды.

        Берёт state.last_command (контракт v1.2); без него — None.
        """
        last: Command | None = state.last_command if state else None
        if last is None or last.intent not in (Intent.LIST, Intent.SEARCH):
            return None
        if _FULL_QUESTION.match(clean):
            # 25.10: «Что у меня в субботу?» после поиска — новая полная команда, а не уточнение
            return None
        slots = last.slots.model_copy(deep=True)
        mf = _ONLY_FILTER.match(clean)
        if mf:  # «только прошедшие», «а только встречи?» — фильтр к прошлому списку/поиску
            word = mf.group(1)
            if word.startswith(("прошедш", "прошл", "стар")):
                slots.tense = "past"
            elif word.startswith(("будущ", "предстоящ", "новые")):
                slots.tense = "future"
            else:
                slots.type = self._type_by_noun(word)
            return self._cmd(last.intent, t, slots, 0.9)
        mt = _TYPE_FOLLOW.match(clean)
        if mt and last.intent == Intent.LIST:  # «а встречи?» после «что у меня в понедельник»
            slots.type = self._type_by_noun(mt.group(1)) if mt.group(1) != "дела" else None
            return self._cmd(Intent.LIST, t, slots, 0.9)
        if _NEXT_AFTER.match(clean) and slots.when and slots.when.is_period:
            shifted_next = self._shift_period("а на следующей", last)
            if shifted_next is not None:
                slots.when = shifted_next
                return self._cmd(last.intent, t, slots, 0.9)
        shifted = self._shift_period(clean, last)
        if shifted is not None:
            slots.when = shifted  # «А на следующей?», «на следующей?» после «на этой неделе»
            return self._cmd(last.intent, t, slots, 0.9)
        if not re.match(r"^(?:а|и|ну а|а если|а что)\b", clean) and not self._only_dates(t, dp):
            return None
        changed = False
        if dp.found and self._only_dates(t, dp):
            slots.when = dp.spec
            changed = True
        rest = self._clean(remove_spans(t, dp.spans)) if dp.found else clean
        if re.search(r"(?<![а-я])(следующ\w*|ближайш\w*|потом|дальше|после)(?![а-я])", rest):
            slots.tense, slots.when, changed = "future", None, True
        elif re.search(
            r"(?<![а-я])(предыдущ\w*|прошл\w*|до этого|раньше|перед этим)(?![а-я])", rest
        ):
            slots.tense, slots.when, changed = "past", None, True
        ls = self.ents.lemmas(t)
        ppl = self.ents.people(t, ls)
        orgs = self.ents.organizations_in(t, ls)
        if ppl or orgs:
            slots.participants = ppl
            slots.organization = _first(orgs)
            changed = True
        if not changed:
            return None
        return self._cmd(last.intent, t, slots, 0.9)

    @staticmethod
    def _shift_period(clean: str, last: Command) -> TimeSpec | None:
        m = re.fullmatch(
            r"(?:(?:а|и|ну а|ну|а если) )?(?:на|в|за) (следующ\w*|прошл\w*|предыдущ\w*)", clean
        )
        w = last.slots.when
        if not m or w is None or w.start is None or w.end is None or not w.is_period:
            return None
        sign = 1 if m.group(1).startswith("след") else -1
        days = (w.end - w.start).days
        if 28 <= days <= 31:
            from .dates import _add_months_keep_day

            start = w.start.replace(day=1)
            ns = start.replace(
                year=_add_months_keep_day(start.date(), sign).year,
                month=_add_months_keep_day(start.date(), sign).month,
            )
            ne = ns.replace(
                year=_add_months_keep_day(ns.date(), 1).year,
                month=_add_months_keep_day(ns.date(), 1).month,
            )
        else:
            from datetime import timedelta

            ns, ne = w.start + timedelta(days=sign * days), w.end + timedelta(days=sign * days)
        return TimeSpec(text=clean, start=ns, end=ne, is_period=True, has_date=True)

    def _only_dates(self, t: str, dp: DateParse) -> bool:
        rest = self._clean(remove_spans(t, dp.spans))
        rest = re.sub(
            r"(?<![а-я])(а|и|ну|что|там|у меня|а у меня|по планам)(?![а-я])", " ", rest
        ).strip()
        return rest == ""

    def _declares_meeting(self, t: str, clean: str, dp: DateParse) -> bool:
        if not dp.found:
            return False
        body = self._clean(remove_spans(t, dp.spans))
        body = re.sub(r"^(?:у меня (?:будет )?|будет |а |и )", "", body)
        return bool(MEETING_HEAD.match(body))

    @staticmethod
    def _is_plain_list(clean: str) -> bool:
        return bool(
            re.fullmatch(
                r"(?:а |ну )?(?:что|какие|какой) (?:у меня|у нас)(?:"
                r" (?:по планам|в планах|запланировано|сейчас))?",
                clean,
            )
            or re.fullmatch(
                r"(?:покажи|выведи|какие|какие у меня|покажи мои|покажи все)(?: все| мои| все мои)?"
                r"(?: (?:невыполненные|выполненные|открытые|закрытые|сделанные|несделанные|"
                r"текущие|активные|просроченные))? (?:встречи|"
                r"задачи|напоминания|дела|события|записи|планы)"
                r"(?: у меня)?",
                clean,
            )
        )

    def _starts_with_infinitive(self, t: str) -> bool:
        words = re.findall(r"[а-яёА-ЯЁ]+", t)
        if not words:
            return False
        p = self.ents.morph.parse(words[0].lower())[0]
        return p.tag.POS == "INFN"

    def _looks_like_search_phrase(self, t: str) -> bool:
        ls = self.ents.lemmas(t)
        if not ls or len(ls) > 6:
            return False
        has_entity = bool(self.ents.people(t, ls) or self.ents.organizations_in(t, ls))
        has_type = self.ents.item_type(t, ls) is not None
        has_verb = any(
            self.ents.morph.parse(lm.orig.lower())[0].tag.POS in ("VERB", "INFN") for lm in ls
        )
        return (has_entity or has_type) and not has_verb

    # ---------- конструкторы команд ----------

    @staticmethod
    def _cmd(intent: Intent, text: str, slots: Slots, conf: float) -> Command:
        return Command(intent=intent, slots=slots, confidence=conf, source="rules", raw_text=text)

    def _type_filter(self, t: str, include_task: bool) -> ItemType | None:
        typ = self.ents.item_type(t)
        if typ == ItemType.TASK and not include_task:
            return None  # «задачу про презентацию» — в речи «задача» значит «любая запись»
        return typ

    def _capability_question(self, clean: str) -> bool:
        m = CAPABILITY.match(clean)
        if not m:
            return False
        if clean.split()[0 if not clean.startswith(("а ", "и ")) else 1] in ("умеешь", "умеете"):
            return True
        return self._infinitive(m.group(1)) and self._imperfective(m.group(1))

    def _infinitive(self, word: str) -> bool:
        return any(p.tag.POS == "INFN" for p in self.ents.morph.parse(word.lower()))

    def _imperfective(self, word: str) -> bool:
        """Есть несовершенный разбор: «переносить» двувидовое — для вопроса «можешь ли» это impf."""
        return any(
            p.tag.POS == "INFN" and "impf" in p.tag for p in self.ents.morph.parse(word.lower())
        )

    def _list_upcoming(self, t: str, now: datetime) -> Command:
        """«Покажи все мои дела» — всё предстоящее: сегодня + UPCOMING_DAYS дней."""
        start = now.replace(hour=0, minute=0, second=0, microsecond=0)
        when = TimeSpec(
            text=t,
            start=start,
            end=start + timedelta(days=UPCOMING_DAYS),
            is_period=True,
            has_date=False,
        )
        typ = self._type_by_noun(self._clean(t))
        if self._clean(t).endswith("дела"):
            typ = None  # «дела» — любые записи
        slots = Slots(type=typ, when=when, tense="future")
        return self._cmd(Intent.LIST, t, slots, 0.92)

    def _list(self, t: str, now: datetime, dp: DateParse) -> Command:
        when = dp.spec
        if when is None and self._is_plain_list(self._clean(t)) and not self.ents.item_type(t):
            when = self.dates.resolve("сегодня", now, "period")
        clean = self._clean(t)
        status = (
            ItemStatus.OPEN
            if STATUS_OPEN.search(clean)
            else ItemStatus.DONE
            if STATUS_DONE.search(clean)
            else None
        )
        slots = Slots(
            type=self._type_filter(t, include_task=True),
            when=when,
            status=status,
            tense=self.ents.tense(t),
        )
        return self._cmd(Intent.LIST, t, slots, 0.92 if when else 0.8)

    def _search(self, t: str, now: datetime, dp: DateParse, confidence: float = 0.9) -> Command:
        ls = self.ents.lemmas(t)
        rest = remove_spans(t, dp.spans) if dp.found else t
        slots = Slots(
            type=self._type_filter(t, include_task=False),
            participants=self.ents.people(t, ls),
            organization=_first(self.ents.organizations_in(t, ls)),
            query=self.ents.expand_query(rest),
            tense=self.ents.tense(t),
            when=dp.spec if dp.found else None,
        )
        return self._cmd(Intent.SEARCH, t, slots, confidence)

    def _create(self, t: str, now: datetime, conf: float) -> Command:
        dp = self._create_dates(t, now)
        nt = normalize(t)
        spans = list(dp.spans)
        duration = None
        for m in _DURATION.finditer(nt.text):
            a, b = nt.orig_span(m.start(), m.end())
            if any(not (b <= x or a >= y) for x, y in dp.spans):
                continue
            n_raw, unit = m.group(1), m.group(2)
            n = 1.5 if n_raw == "полтора" else float(n_raw or 1)
            duration = int(n * (60 if unit.startswith("час") else 1))
            spans.append((a, b))
            break
        when = dp.spec
        # второе время во фразе: «может быть, в 5 вечера, может быть, в 6:00» → спросить
        rest = remove_spans(t, spans)
        dp2 = self.dates.extract(rest, now, "point") if when is not None else None
        if (
            when is not None
            and dp2 is not None
            and dp2.spec is not None
            and dp2.spec.has_time
            and when.has_time
            and not dp.recurrence
        ):
            spans += dp2.spans
            # QA-20: перечисление («в восемь и в 14:40», «одну … вторую …») — это несколько
            # записей → « и »; выбор («может быть, в 5, может быть, в 6») → « или »
            enum = bool(
                MULTI_ITEMS.search(self._clean(t))
                or re.search(r"(?<![а-яё])(?:и|втор\w*|одн\w+|потом|затем)(?![а-яё])", rest.lower())
            )
            sep = " и " if enum else " или "
            when = when.model_copy(
                update={"ambiguous": True, "text": f"{when.text}{sep}{dp2.spec.text}"}
            )
            conf = min(conf, PENALTY_CONF)
        clean = self._clean(t)
        if MULTI_ITEMS.search(clean):  # «Две пары: …» — несколько записей сразу пока не создаём
            conf = min(conf, PENALTY_CONF)
            if when is not None:
                when = when.model_copy(update={"ambiguous": True})
            else:
                when = TimeSpec(text=t, ambiguous=True)
        body = remove_spans(t, spans)
        is_reminder = bool(re.search(r"(?<![а-я])(напомн|напомин|не забу)", clean))
        if is_reminder and not re.search(r"(?<![а-я])(напомн|напомин)", clean):
            # «не забудь, что у меня собеседование в 11» — это событие, а не напоминание
            is_reminder = not self._mentions_meeting(clean)
        title = sanitize_title(self._make_title(body))
        if title and TIME_WORDS.search(title):
            # в названии осталось время или дата — правила что-то не разобрали, решает LLM
            conf = min(conf, PENALTY_CONF)
        typ = ItemType.REMINDER if is_reminder else ItemType.TASK
        if not is_reminder and self._mentions_meeting(clean) and not _EXPLICIT_TASK.search(clean):
            typ = ItemType.MEETING  # «поставь задачу … созвониться» — сказано «задачу», это задача
        # длительность и конец согласованы: «с 13:30 до 15:30» ↔ «в 10 на два часа»
        if when is not None and when.start is not None and when.has_time:
            if when.end is not None and duration is None and not when.ambiguous:
                duration = int((when.end - when.start).total_seconds() // 60) or None
            elif when.end is None and duration:
                when = when.model_copy(update={"end": when.start + timedelta(minutes=duration)})
        ls = self.ents.lemmas(body)
        slots = Slots(
            type=typ,
            title=title or None,
            when=when,
            duration_min=duration,
            participants=self.ents.people(body, ls),
            organization=_first(self.ents.organizations_in(body, ls)),
            recurrence=dp.recurrence,
        )
        return self._cmd(Intent.CREATE, t, slots, conf)

    def _create_dates(self, t: str, now: datetime) -> DateParse:
        """Дата новой записи. Прошлое не предпочитаем («встречались … поставь на среду»):
        если после глагола создания названа дата — берём её; «вчера», «в прошлый раз»
        при другой дате во фразе — контекст, а не время записи."""
        trig = list(CREATE_TRIGGER.finditer(t))
        if trig:
            tail_start = trig[-1].end()
            tail = t[tail_start:]
            dpt = self.dates.extract(tail, now, "point", prefer_past=False)
            if dpt.found and tail_start > 0 and self.dates.extract(t[:tail_start], now).found:
                spans = [(a + tail_start, b + tail_start) for a, b in dpt.spans]
                head_dp = self.dates.extract(t[:tail_start], now, "point", prefer_past=False)
                return DateParse(
                    spec=dpt.spec,
                    has_date=dpt.has_date,
                    spans=head_dp.spans + spans,  # из названия убираем обе даты
                    deadline=dpt.deadline,
                    recurrence=dpt.recurrence,
                )
        past = _rx(r"вчера|позавчера|в прошлый раз|на прошлой неделе|раньше|давно")
        if past.search(t):
            stripped = past.sub(" ", t)
            dps = self.dates.extract(stripped, now, "point", prefer_past=False)
            if dps.found:
                full = self.dates.extract(t, now, "point", prefer_past=False)
                return DateParse(
                    spec=dps.spec,
                    has_date=dps.has_date,
                    spans=full.spans,
                    deadline=dps.deadline,
                    recurrence=dps.recurrence,
                )
        return self.dates.extract(t, now, "point", prefer_past=False)

    @staticmethod
    def _mentions_meeting(clean: str) -> bool:
        """«встречу / созвон / пару» в любом месте фразы, кроме «к встрече», «итоги встречи»."""
        for m in MEETING_ANY.finditer(clean):
            before = clean[: m.start()].split()
            if not before or before[-1] not in _MEETING_BLOCKERS:
                return True
        return False

    def _make_title(self, body: str) -> str:
        body = _TITLE_ANY_JUNK.sub(" ", body)
        s = _LEAD_FILLER.sub("", body.strip())
        # убрать триггер («напомни мне», «поставь задачу», «у меня») — первое вхождение
        s = _CREATE_PREFIX_RE.sub("", s, count=1).strip(" ,")
        s = _LEAD_FILLER.sub("", s)
        s = _THAT.sub("", s)
        s = _TITLE_LEAD_JUNK.sub("", s)  # «нам будет сдать…», «задачу поставить починить…»
        s = _TAIL_FILLER.sub("", s).strip(" ,.")
        if not s:
            return ""
        words = s.split()
        # голова-существительное в им. падеж: «встречу с командой» → «Встреча с командой»
        p = self.ents.morph.parse(words[0].lower())[0]
        if p.tag.POS == "NOUN" and "accs" in p.tag:
            inf = p.inflect({"nomn"})
            if inf:
                words[0] = inf.word
        out = []
        for w in words:
            core = re.match(r"([А-Яа-яЁё]+)(.*)", w)
            if core and "е" in core.group(1).lower():
                q = self.ents.morph.parse(core.group(1).lower())[0]
                if q.tag.POS == "NOUN" and q.word.replace("ё", "е") == core.group(1).lower():
                    fixed = q.word
                    if core.group(1)[0].isupper():
                        fixed = fixed[0].upper() + fixed[1:]
                    w = fixed + core.group(2)
            out.append(w)
        s = " ".join(out)
        return s[0].upper() + s[1:]

    def _target_slots(self, part: str, now: datetime, intent: Intent) -> Slots:
        # 24.10: «ту встречу с Марией что была», «задача про акт была на понедельник»,
        # «звонок Анне который был на третье»: прошедшее время описывает запись, а не дату
        part = _TARGET_NOISE.sub(" ", part)
        part = _TARGET_TENSE.sub(" ", part)
        part = _DONE_PARTICIPLE.sub(" ", part)  # «смета уже проверена» → «смета»
        part = re.sub(r"(?i)(?<![а-яё])уже(?![а-яё])", " ", part)
        stripped = _TARGET_DEMONSTR.sub(" ", part)
        rest_ref = _REF_PARTICLES.sub(" ", stripped)
        rest_ref = re.sub(
            r"(?i)(?<![а-яё])(?:задач\w*|встреч\w*|запис\w*|напоминани\w*|созвон\w*|дел\w*)"
            r"(?![а-яё])",
            " ",
            rest_ref,
        )
        if rest_ref.strip(
            " ,.?!"
        ):  # «ту встречу с Марией» → «встречу с Марией»; «эту задачу» — ссылка
            part = stripped
        part = re.sub(r"\s{2,}", " ", part).strip()
        dp = (
            self.dates.extract(part, now, "period", prefer_past=bool(_TARGET_PAST.search(part)))
            if part.strip()
            else DateParse(spec=None)
        )
        desc = remove_spans(part, dp.spans) if dp.found else part
        desc = re.sub(r"(?<![а-яё])(?:котор\w+|что стоит|что была|что было)(?![а-яё])", " ", desc)
        desc = _target_noun_fix(desc)
        low = self._clean(desc)
        # «последнюю задачу / запись / встречу» — самая поздно созданная запись (чат 2)
        mark: str | None = None
        if LAST_WORDS.search(low):
            mark = MARK_LAST
        elif ALL_WORDS.search(low):  # «все завтрашние встречи», «отмени всё»
            mark = MARK_ALL
        if mark is not None:
            return Slots(
                type=self._type_by_noun(low),
                when=dp.spec if dp.found else None,
                participants=self.ents.people(desc),
                organization=_first(self.ents.organizations_in(desc)),
                target=ItemRef(description=mark),
            )
        desc = _LEAD_FILLER.sub("", desc.strip(" ,"))
        desc = _THAT.sub("", desc)
        desc = re.sub(
            r"(?<![а-яё])(?:как (?:выполненн\w+|сделанн\w+|готов\w*)"
            r"|выполненн\w+|сделанн\w+|завершённ\w+|завершенн\w+|пожалуйста|можно|нужно|надо|пора|"
            r"время|дату|срок|все|всё)(?![а-яё])",
            "",
            desc,
            flags=re.IGNORECASE,
        )
        desc = _REF_PARTICLES.sub(" ", desc)  # «эту же задачу ещё» → «эту задачу»
        desc = re.sub(r"\s{2,}", " ", desc).strip(" ,.?!")
        pronoun = bool(PRONOUN.search(self._clean(desc))) and len(desc.split()) <= 3
        # «смету по мобильному приложению я проверил» → «проверить смету по мобильному приложению»
        words = desc.split()
        verbs = [
            i
            for i, w in enumerate(words)
            if (q := self.ents.morph.parse(w.lower().strip(",."))[0]).tag.POS == "VERB"
            and "past" in q.tag
        ]
        if verbs:
            i = verbs[0]
            inf = self.ents.infinitive(words[i].strip(",."))
            rest = [
                w for j, w in enumerate(words) if j != i and w.lower() not in ("я", "уже", "мы")
            ]
            words = [inf, *rest]
        desc = " ".join(words)
        if pronoun:
            desc_wo = PRONOUN.sub("", desc).strip()
            desc = desc_wo or ""
        ls = self.ents.lemmas(desc)
        return Slots(
            type=self._type_filter(desc, include_task=False),
            when=dp.spec if dp.found else None,
            participants=self.ents.people(desc, ls),
            organization=_first(self.ents.organizations_in(desc, ls)),
            query=self.ents.expand_query(desc, lemmas=ls),
            target=ItemRef(pronoun=pronoun, description=desc or None),
        )

    @staticmethod
    def _type_by_noun(low: str) -> ItemType | None:
        for stem, typ in _TYPE_BY_NOUN:
            if re.search(r"(?<![а-яё])" + stem, low):
                return typ
        return None

    def _target_cmd(
        self, intent: Intent, t: str, now: datetime, verb_re: re.Pattern[str]
    ) -> Command:
        body = verb_re.sub("", t, count=1)
        body = re.sub(r"^[\s,]*(?:мне|пожалуйста|что|,)+[\s,]*", "", body)
        slots = self._target_slots(body, now, intent)
        if intent == Intent.COMPLETE:
            slots.status = ItemStatus.DONE
        conf = 0.9 if (slots.target and (slots.target.description or slots.target.pronoun)) else 0.6
        return self._cmd(intent, t, slots, conf)

    def _first_command(self, t: str, now: datetime) -> str:
        """Две команды в одной фразе — оставляем первую (adversarial 24.10, two_commands).

        «перенеси созвон на пятницу и удали звонок Анне» → «перенеси созвон на пятницу»;
        «перенеси созвон с Альфой на понедельник а звонок Анне на вторник» → первая часть;
        «перенеси отчёт и созвон с Орбитой на пятницу» → дата из второй части к первой.
        «смету проверил и протокол Елене отправил» → «смету проверил».
        """
        m = _SECOND_CMD.search(t)
        if m and m.start() > 0:
            return t[: m.start()]
        if not UPDATE.match(self._clean(t)) and not self._done_statement(self._clean(t)):
            return t
        for mm in re.finditer(r"[\s,]+(?:и|а)\s+", t):
            left, right = t[: mm.start()], t[mm.end() :]
            lc, rc = self._clean(left), self._clean(right)
            if UPDATE.match(lc):
                dl = self.dates.extract(left, now, "point")
                dr = self.dates.extract(right, now, "point")
                if not dr.spans or UPDATE.search(rc):
                    continue
                if dl.spans:
                    return left
                a, b = sorted(dr.spans)[-1]
                return f"{left} {right[a:b]}"
            elif self._done_statement(lc) and self._done_statement(rc):
                return left
        return t

    def _implicit_update(
        self, t: str, clean: str, now: datetime, create_pos: float, is_question: bool
    ) -> Command | None:
        """Перенос без глагола: «было бы удобнее встретиться с Марией в воскресенье»."""
        if is_question or create_pos <= len(clean) or UPDATE.search(clean) or DELETE.search(clean):
            return None
        m = _DAVAI_MOVE.match(t)
        if m:
            target, new = m.group("target"), m.group("new")
            new_core = re.sub(r"(?i)^на\s+", "", new)
            nd = self.dates.extract(new_core, now, "point")
            low = self._clean(target)
            if (
                nd.found
                and self._only_dates(new_core, nd)
                and (STUB_REFERENCE.search(low) or self.ents.people(target))
            ):
                target = _IMPLICIT_MOVE.sub(" ", target)
                return self._finish_update(t, target, new, None, now)
        if _IMPLICIT_MOVE.search(t):
            dp = self.dates.extract(t, now, "point")
            if not dp.spans:
                return None
            rest = _IMPLICIT_MOVE.sub(" ", t)
            rest = re.sub(r"(?i)(?<![а-яё])(?:давай(?:те)?|мне|было бы|лучше)(?![а-яё])", " ", rest)
            dpr = self.dates.extract(rest, now, "point")
            if not dpr.spans:
                return None
            a, b = sorted(dpr.spans)[-1]
            target, new = rest[:a] + " " + rest[b:], rest[a:b]
            low = self._clean(target)
            if STUB_REFERENCE.search(low) or self.ents.people(target):
                return self._finish_update(t, target, new, None, now)
        return None

    def _done_statement(self, clean: str) -> bool:
        """«всё сделал с итогами для Максима», «позвонил уже», «смета уже проверена»."""
        if _DONE_PARTICIPLE.search(clean):
            return True
        for w in clean.split():
            if w in _DONE_EXCLUDE or len(w) < 4:
                continue
            q = self.ents.morph.parse(w)[0]
            if q.tag.POS == "VERB" and "past" in q.tag and "perf" in q.tag:
                return True
        return False

    def _update(self, t: str, now: datetime) -> Command:
        m = UPDATE.search(t)
        assert m
        verb = m.group(0).lower()
        body = (t[: m.start()] + " " + t[m.end() :]).strip()
        body = _LEAD_FILLER.sub("", body)
        new_title = None
        target_part, new_part = body, ""
        if verb.startswith(("переименуй", "переименовать")) or "название" in body.lower():
            mm = re.search(r"(.*?)(?:\s+(?:в|на)\s+)[«\"]?(.+?)[»\"]?$", body)
            if mm:
                target_part, new_title = mm.group(1), mm.group(2)
                target_part = re.sub(r"название\s*", "", target_part).strip()
                new_title = new_title[:1].upper() + new_title[1:]
        else:
            # ищем «на …» с датой/временем — это новое время; всё до него — описание цели
            for mm in re.finditer(r"(?<![а-яё])на\s", body, flags=re.IGNORECASE):
                cand = body[mm.start() :]
                sm = SHIFT_SPAN.match(cand)
                if sm and (shift := parse_shift(sm.group(0))) is not None:
                    # «на час позже сдвинь созвон с Альфой»: цель может стоять и после сдвига
                    target_part = body[: mm.start()] + " " + cand[sm.end() :]
                    new_part = shift_text(shift)
                    break
                ncand = re.sub(r"\s*[.,!?;]+\s*$", "", normalize(cand).text)  # «на 19.»
                if re.fullmatch(
                    r"на \d{1,2}(?: (?:час|часа|часов))?(?: (?:утра|дня|вечера|ночи))?", ncand
                ):
                    target_part, new_part = (
                        body[: mm.start()],
                        "в " + cand[3:],
                    )  # «на 11» в переносе = время
                    break
                dp = self.dates.extract(cand, now, "point")
                if dp.found and self._only_dates(cand, dp):
                    target_part, new_part = body[: mm.start()], cand
                    break
            if not new_part:  # прежнее правило: дата сразу после «на», хвост — что угодно
                for mm in re.finditer(r"(?<![а-яё])на\s", body, flags=re.IGNORECASE):
                    cand = body[mm.start() :]
                    dp = self.dates.extract(cand, now, "point")
                    if dp.found and dp.spans and dp.spans[0][0] <= 3:
                        # «на воскресенье встречу с Марией сдвинь»: хвост после даты — тоже цель
                        end = 0
                        for x, y in sorted(dp.spans):
                            if end == 0 or x <= end + 4:  # «на четвёртое ноября в десять»
                                end = max(end, y)
                        target_part = body[: mm.start()] + " " + cand[end:]
                        new_part = cand[:end]
                        break
            if not new_part:  # «на после праздников», «на конец недели» — дату надо уточнить
                vm = re.search(
                    r"(?<![а-яё])на\s+(?:после|потом|попозже|позже|другой|другое|друг\w+|конец|"
                    r"начало|середину)(?![а-яё]).*$",
                    body,
                    flags=re.IGNORECASE,
                )
                if vm:
                    target_part, new_part = body[: vm.start()], vm.group(0)
            if not new_part:
                dp_all = self.dates.extract(body, now, "point")
                if dp_all.spans:
                    a, b = dp_all.spans[-1]
                    # последний фрагмент — новое время, если до него есть цель
                    target_part, new_part = body[:a] + body[b:], body[a:b]
        return self._finish_update(t, target_part, new_part, new_title, now)

    def _finish_update(
        self, t: str, target_part: str, new_part: str, new_title: str | None, now: datetime
    ) -> Command:
        slots = self._target_slots(target_part, now, Intent.UPDATE)
        if (
            new_part
            and parse_shift(new_part) is not None
            and SHIFT_SPAN.fullmatch(new_part.strip())
        ):
            # сдвиг: «на 30 минут раньше» — не «30-е число»
            slots.new_when = TimeSpec(text=new_part.strip())
        elif new_part:
            nd = self.dates.extract(new_part, now, "point")
            spec = nd.spec
            if spec is not None:
                # «… в субботу на 19:00»: время без даты берём на дату цели
                if not nd.has_date and spec.has_time and slots.when and slots.when.start:
                    start = slots.when.start.replace(hour=spec.start.hour, minute=spec.start.minute)  # type: ignore[union-attr]
                    spec = spec.model_copy(update={"start": start, "end": None, "has_date": True})
                if (
                    spec.start is not None
                    and spec.has_date
                    and spec.start.date() == now.date()
                    and re.search(
                        r"(?i)понедельник|вторник|сред|четверг|пятниц|суббот|воскресен", new_part
                    )
                    and not re.search(r"(?i)эт[уиот]\w*|сегодня", new_part)
                ):
                    # «перенеси на пятницу» в пятницу — следующая пятница, а не сегодня
                    spec = spec.model_copy(
                        update={
                            "start": spec.start + timedelta(days=7),
                            "end": spec.end + timedelta(days=7) if spec.end else None,
                        }
                    )
                slots.new_when = spec
            else:
                shift = parse_shift(new_part)
                slots.new_when = TimeSpec(text=new_part.strip(), ambiguous=shift is None)
        slots.new_title = new_title
        conf = 0.9 if (slots.new_when or new_title) else 0.7
        return self._cmd(Intent.UPDATE, t, slots, conf)

    def _correction(
        self, t: str, clean: str, now: datetime, state: DialogState | None = None
    ) -> Command | None:
        """«Нет, в 11» / «не в 10, а в 11» → перенос последней записи."""
        last_cmd = state.last_command if state else None
        # «ой нет, на одиннадцать», «а лучше в воскресенье» — после только что созданной записи
        lead = r"(?:ой\s+)?(?:нет|не|а нет)"
        if last_cmd is not None and last_cmd.intent in (Intent.CREATE, Intent.UPDATE):
            lead = r"(?:(?:ой\s+)?(?:нет|не|а нет)|(?:а\s+|нет\s+)?лучше|давай лучше)"
        m = re.match(r"^" + lead + r"\s+(?:(?:в|на)\s+\S+\s+а\s+)?(.+)$", clean)
        if not m:
            return None
        rest_orig = re.sub(
            r"^\s*" + lead.replace("\\s+", "[\\s,]+") + r"[\s,]+(?:(?:в|на)\s+\S+[\s,]+а\s+)?",
            "",
            t,
            flags=re.IGNORECASE,
        )
        dp = self.dates.extract(rest_orig, now, "point")
        if not dp.found or not self._only_dates(rest_orig, dp):
            return None
        spec = dp.spec
        last: Command | None = state.last_command if state else None
        if (
            spec
            and spec.start
            and spec.has_time
            and not dp.has_date
            and last is not None
            and last.slots.when
            and last.slots.when.start
        ):
            spec = spec.model_copy(
                update={
                    "start": last.slots.when.start.replace(
                        hour=spec.start.hour, minute=spec.start.minute
                    ),
                    "has_date": True,
                }
            )
        slots = Slots(target=ItemRef(pronoun=True), new_when=spec)
        return self._cmd(Intent.UPDATE, t, slots, 0.88)


_SHIFT_UNITS = r"(полчаса|полчасика|минут\w*|мин|час\w*|дн\w*|день|сутки|недел\w*)"
_SHIFT_DIR = r"(позже|попозже|раньше|пораньше|вперед|вперёд|назад)"
# фрагмент сдвига в исходном тексте: «на час позже», «на пару дней», «на недельку»
SHIFT_SPAN = re.compile(
    r"(?<![а-яё])на\s+(?:(?:\d+(?:[.,]\d+)?|[а-яё]+)\s+){0,2}"
    + _SHIFT_UNITS
    + r"(?:\s+"
    + _SHIFT_DIR
    + ")?",
    re.IGNORECASE,
)
_SHIFT_N = {"полтора": 1.5, "пару": 2, "пара": 2, "пары": 2, "несколько": 3, "пол": 0.5}


def parse_shift(text: str) -> int | None:
    """«на час позже» → +60, «на 30 минут раньше» → −30 (минуты).

    Для переноса относительно текущего времени записи. 24.10: «на полчаса пораньше»,
    «на часик попозже», «на пару дней», «на недельку» (дни и недели без направления — вперёд).
    """
    nt = normalize(text).text.replace("ё", "е")
    m = re.search(
        r"на (?:(\d+(?:[.,]\d+)?|полтора|пару|пара|пары|несколько) )?"
        r"(полчаса|полчасика|минут\w*|мин|час\w*|дн\w*|день|сутки|недел\w*)"
        r"(?: (позже|попозже|раньше|пораньше|вперед|назад))?(?![а-я])",
        nt,
    )
    if not m:
        return None
    unit, direction = m.group(2), m.group(3)
    if unit == "неделе":
        return None  # «на неделе» — период, а не сдвиг
    if direction is None and not unit.startswith(("дн", "день", "сутки", "недел")):
        return None  # «на час» без направления — длительность или время, не сдвиг
    raw = m.group(1)
    if unit.startswith("полчас"):
        n = 0.5 if raw is None else _SHIFT_N.get(raw, 1) * 0.5
        unit = "час"
    elif raw is None:
        n = 1.0
    elif raw in _SHIFT_N:
        n = _SHIFT_N[raw]
    else:
        n = float(raw.replace(",", "."))
    if unit.startswith("недел"):
        mult = 7 * 1440
    elif unit.startswith(("дн", "день", "сутки")):
        mult = 1440
    elif unit.startswith("час"):
        mult = 60
    else:
        mult = 1
    sign = -1 if direction in ("раньше", "пораньше", "назад") else 1
    return int(sign * n * mult)


def shift_text(minutes: int) -> str:
    """Каноническая запись сдвига для new_when.text: диалог читает её через parse_shift."""
    return f"на {abs(minutes)} минут {'позже' if minutes > 0 else 'раньше'}"
