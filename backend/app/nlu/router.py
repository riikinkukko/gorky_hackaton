def sanitize_title(title: str) -> str:
    """Название без мата, пустых «, ,» и служебных слов на краях. Пустая строка — нет названия."""
    t = PROFANITY.sub(" ", title)
    t = re.sub(r"\s*,(?:\s*,)+", ",", t)  # «, ,» → «,»
    t = re.sub(r"\s+([,.!?;:])", r"\1", t)
    t = re.sub(r"\s{2,}", " ", t).strip(" ,.;:!?—–-")
    prev = None
    while prev != t:
        prev = t
        t = _TITLE_EDGE.sub("", t).strip(" ,.;:!?—–-")
    if not re.search(r"[A-Za-zА-Яа-яЁё]", t):
        return ""
    return t[:1].upper() + t[1:]


