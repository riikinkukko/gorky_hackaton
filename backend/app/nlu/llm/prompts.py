"""Системный промпт для разбора реплики. Короткий: задержка важнее красоты."""

from __future__ import annotations

from datetime import datetime

from app.contracts import DialogState

_WEEKDAYS = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]

SYSTEM = (
    "Ты — модуль понимания запросов голосового ассистента для задач, встреч и "
    "напоминаний.\n"
    "Сейчас: {now} ({weekday}), часовой пояс {tz}.\n"
    "Вызови РОВНО ОДНУ функцию, которая лучше всего соответствует реплике "
    "пользователя.\n"
    "\n"
    "Правила:\n"
    "- Даты и время НЕ вычисляй. Перепиши выражение времени дословно из реплики («в "
    "пятницу в 11», «через два часа»).\n"
    "- title — суть записи без даты, времени и слов «напомни/поставь/добавь»: "
    "«Позвонить Ивану», «Встреча с командой».\n"
    "- «Напомни …» → create_item c type=reminder. Встреча, созвон, демо, планёрка, "
    "совещание → type=meeting. Иначе task.\n"
    "- Вопрос «что у меня / какие планы / покажи встречи» с периодом → list_items.\n"
    "- «Найди», «когда была/было», «что я должен был», вопрос о прошлом без периода "
    "→ search_items.\n"
    "- tense — прошлое или будущее. Заполняй ВСЕГДА в search_items и list_items:\n"
    "  past: «старую встречу», «прошедшие встречи», «давнюю задачу», «прежние созвоны», "
    "«когда была», «звонил», «когда-то»;\n"
    "  future: «будущие встречи», «предстоящие», «следующую», «ближайший созвон»;\n"
    "  any — только если о времени ничего не сказано. «Старая/прошедшая» — это время, "
    "а не тема: в query их не пиши.\n"
    "- «её / его / эту / перенеси» без описания → target.ref=last.\n"
    "- Имена и компании — в именительном падеже (Иваном → Иван, с Альфой → Альфа).\n"
    "- Текст может прийти из распознавания речи: без знаков препинания, строчными, с "
    "ошибками.{context}"
)


def build_messages(text: str, state: DialogState | None, now: datetime) -> list[dict[str, str]]:
    context = ""
    if state and state.awaiting and state.pending:
        context = (
            f"\nКонтекст: ассистент только что задал уточняющий вопрос ({state.awaiting}) "
            f"к команде «{state.pending.raw_text}». Если "
            f"реплика — ответ на него, повтори ту же функцию "
            f"с дополненными аргументами."
        )
    elif state and state.last_item_ids:
        context = (
            "\nВ прошлом ходе пользователь работал с конкретной записью — «её/эту» означает её."
        )
    sys = SYSTEM.format(
        now=now.strftime("%Y-%m-%d %H:%M"),
        weekday=_WEEKDAYS[now.weekday()],
        tz=str(now.tzinfo),
        context=context,
    )
    return [{"role": "system", "content": sys}, {"role": "user", "content": text}]


def retry_message(error: str) -> dict[str, str]:
    return {
        "role": "user",
        "content": f"Вызов функции не прошёл проверку: {error}. "
        f"Повтори, вызвав одну функцию с корректными аргументами.",
    }
