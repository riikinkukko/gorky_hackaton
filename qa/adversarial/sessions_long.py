def say(text, action=None, *, dead=False, note=None, **e):
    t = {"say": text}
    if action is not None:
        e["action"] = action
    if "title" in e:
        v = e.pop("title")
        e["title_contains"] = [v] if isinstance(v, str) else v
    if e:
        t["expect"] = e
    if dead:
        t["allow_dead_end"] = True
    if note:
        t["note"] = note
    return t


def click(label, action=None, **e):
    t = say("", action, **e)
    t.pop("say")
    return {"click": label, **t}


def ls(text, date=None, period=None, **e):
    e.setdefault("must_not", NC)
    return say(text, "listed", intent=LIST, date=date, period=period, **e)


def fnd(text, **e):
    e.setdefault("must_not", NC)
    return say(text, "found", intent=SEARCH, **e)


def mk(text, type_, date=None, time=None, action="created", **e):
    if action == "created" or (isinstance(action, list) and "created" in action and len(action) == 1):
        e.setdefault("intent", CREATE)
    return say(text, action, type=type_, date=date, time=time, **e)


def upd(text, date=None, time=None, action="updated", **e):
    e.setdefault("must_not", NC)
    return say(text, action, date=date, time=time, **e)


